export function getProvincesByCountryCode(countryCode: string): CountryProvinceDetail[] {
  const upper = countryCode?.toUpperCase();
  return COUNTRY_PROVINCES_REGISTRY[upper] || [];
}

export function getProvinceById(provinceId: string): CountryProvinceDetail | undefined {
  for (const provList of Object.values(COUNTRY_PROVINCES_REGISTRY)) {
    const found = provList.find(p => p.id === provinceId);
    if (found) return found;
  }
  return undefined;
}
